export type IconName = keyof typeof ICONS;

export function Icon({ name, className = "size-5", title }: { name: IconName; className?: string; title?: string }) {
  const C = ICONS[name];
  return (
    <C
      className={className}
      strokeWidth={1.75}
      aria-hidden={title ? undefined : true}
      role={title ? "img" : undefined}
      aria-label={title}
    />
  );
}
